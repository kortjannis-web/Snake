/**
 * Kampagne: feste Missionen je Welt. Jede Mission ist eine von Hand gebaute Karte, die bei jedem Spielen gleich ist.
 *
 * Karten als Text, eine Zeile je Kartenreihe (alle gleich breit, Breite und Hoehe ganze Bloecke, siehe MISSION_BLOCK):
 *   #  Berg (gehoert nicht zur Karte, dagegen = vorbei)
 *   .  Wiese
 *   S  Kopf der Schlange beim Start (der Koerper liegt entgegen der Startrichtung dahinter)
 *   A  Apfel (alle liegen von Anfang an da, der zuletzt uebrige leuchtet)
 *   W  Mauer
 *   ~  Teich
 *   G  Giftapfel
 *   F  Frosch
 *   E  Eis (rutschig: dort laesst sich nicht lenken)
 *   R  Kopf einer roten Gegner-Schlange (der Koerper liegt dorthin, wo am meisten Platz ist)
 *   $ * %  Gold, Diamant, Rubin (Schatz: bringen beim ersten Abschluss Aepfel extra)
 * Ab Mission 5:
 *   a  Ameise (sitzt dort, bis die Schlange nah ist)
 *   Y  Stamm eines stehenden Baums (von oben ein Plus: die vier Nachbarn gehoeren dazu). Kommt der Kopf auf 5 Felder
 *      heran, kippt er nach 1 bis 8 Sekunden um (nie auf die Schlange)
 *   H  Haus (zusammenhaengende Felder; je Seite ein Fenster, das Licht wechselt alle paar Sekunden)
 * Ab Mission 11:
 *   Z  Stamm einer grossen Tanne (steht auf 3 x 3 Feldern, faellt 6 Felder weit)
 *   M  kleiner Steingolem
 *   L  Lava (zusammenhaengend ein See, breitet sich aus)
 *   C  Quelle einer Giftwolke (steigt immer wieder auf)
 *   J  Leuchtturm (2 x 2, dreht seinen Lichtkegel)
 *   b  Bienenstock, I Igel
 * Nur im Boss-Level: O Mitte eines Bannkreises, 1 bis 6 Sockel, B Steingolem, T Steintor, k Platz fuer Kristalle,
 *   x Wiese, auf die der Golem nicht tritt
 */
import type { Dir } from './types'

/** Normale Mission, Schatz-Level (Bonus) oder Boss-Level */
export type MissionArt = 'normal' | 'schatz' | 'boss'

export type MissionDef = {
  /** Eindeutig ueber alle Welten, z. B. 'wiese-1' (so steht sie im Speicher) */
  id: string
  welt: 'wiese'
  nr: number
  name: string
  art: MissionArt
  /** Belohnung beim ersten Abschluss (Aepfel) */
  lohn: number
  /** Dazu beim ersten Abschluss: ein Skin (Id aus render/skins.ts), nur hier zu bekommen */
  skin?: string
  /** Noch nicht gebaut: auf der Karte ausgegraut */
  karte?: readonly string[]
  /** Startrichtung der Schlange */
  richtung?: Dir
  /** Startlaenge (mindestens 3) */
  laenge?: number
  /** Startwert fuer den Zufall (Froesche, Gegner): so laeuft die Mission jedes Mal gleich */
  seed?: number
  /** Schneller je Apfel (Prozent, Standard wie im freien Spiel 0,12): spaete Missionen ziehen an */
  tempoProApfel?: number
  /** Eigene Bildgroesse (Boss: die ganze Arena passt ins Bild) */
  bild?: { w: number; h: number }
  /** Kurzer Hinweis beim Start */
  hinweis?: string
  /** Giftwolken aus den Quellen werden so gross (1 Kreuz, 2 Quadrat 3 x 3, 3 mit Spitzen) */
  wolkeStufe?: number
  /** Lavaseen breiten sich um so viele Felder aus */
  lavaMehr?: number
}

