/** Die 10 Missionen der Wiese. 5 ist das Schatz-Level, 10 der Boss (der Steingolem) */
export const WIESE_MISSIONEN: MissionDef[] = NAMEN.map((name, i) => ({
  id: `wiese-${i + 1}`,
  welt: 'wiese',
  nr: i + 1,
  name,
  art: i === 4 ? 'schatz' : i === 9 ? 'boss' : 'normal',
  lohn: MISSION_LOHN[i],
  ...(MISSION_SKINS[i + 1] ? { skin: MISSION_SKINS[i + 1] } : {}),
  ...BAU[i],
}))

export const missionVon = (id: string) => WIESE_MISSIONEN.find((m) => m.id === id) ?? null
